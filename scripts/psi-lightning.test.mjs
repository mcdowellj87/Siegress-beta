import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from '../vendor/three.module.js';
import {createPsiLightning} from '../src/player/psiLightning.js';

test('critical gating, first person cast, grounded geometry, cancellation and camera restoration',()=>{
  const scene=new THREE.Scene(),camera=new THREE.PerspectiveCamera();
  camera.position.set(0,40,0);camera.lookAt(0,30,-125);
  let view='third';
  const psi={isCritical:false,isRegulating:false};
  const hand={hidden:true,style:{}};
  let hits = 0;
  const effect=createPsiLightning({scene,camera,cameraSystem:{get viewMode(){return view},setViewMode(v){view=v}},psionicSystem:psi,heightAtWorld:()=>7,scale:25,handEl:hand,onImpact:()=>hits++});
  assert.equal(effect.cast(),false);
  assert.equal(effect.toggleAiming(),false);
  assert.equal(effect.isAiming,false);
  psi.isCritical=true;psi.isRegulating=true;assert.equal(effect.cast(),false);
  psi.isRegulating=false;assert.equal(effect.cast(),false);
  assert.equal(effect.toggleAiming(),true);
  assert.equal(effect.isCasting,false);
  assert.equal(effect.cast(),true);
  assert.equal(view,'first');assert.equal(hand.hidden,false);
  assert.equal(effect.cast(),false);
  effect.update(.5,true);
  assert.equal(hits,1);
  effect.update(.1,true);assert.equal(hits,1);
  const meshes=scene.children[0].children.filter(c=>c.isMesh);
  assert.equal(meshes.length,11);
  assert.equal(meshes[2].position.y,8);
  const remaining=effect.cooldownRemaining;
  assert.ok(remaining>0);
  effect.update(.1,false);
  assert.ok(effect.cooldownRemaining>0);
  assert.ok(effect.cooldownRemaining<remaining);
  assert.equal(view,'third');assert.equal(hand.hidden,true);assert.equal(effect.isCasting,false);
  assert.equal(scene.children[0].children.filter(c=>c.isMesh).length,0);
  view='first';effect.toggleAiming();effect.update(2,true);effect.cast();
  psi.isCritical=false;effect.update(2,true);
  assert.equal(view,'first');assert.equal(effect.isCasting,false);
  assert.equal(effect.isAiming,true);assert.equal(hand.hidden,false);
  assert.equal(effect.cast(),false);
  assert.equal(effect.toggleAiming(),false);assert.equal(hand.hidden,true);
});

test('center ray hits only terrain and reticle rotates and conforms to its slope',()=>{
 const scene=new THREE.Scene(),camera=new THREE.PerspectiveCamera(75,1,.1,1000);
 const geometry=new THREE.PlaneGeometry(100,100,10,10);geometry.rotateX(-Math.PI/2);
 const positions=geometry.attributes.position;
 for(let i=0;i<positions.count;i++)positions.setY(i,positions.getX(i)*.5);
 geometry.computeVertexNormals();
 const ground=new THREE.Mesh(geometry,new THREE.MeshBasicMaterial());ground.renderOrder=1;scene.add(ground);
 camera.position.set(0,20,30);camera.lookAt(0,0,0);camera.updateMatrixWorld(true);
 const effect=createPsiLightning({scene,camera,cameraSystem:{viewMode:'first',setViewMode(){}},psionicSystem:{isCritical:true,isRegulating:false},heightAtWorld:()=>-100,scale:25,handEl:{style:{}},getGroundMesh:()=>ground});
 effect.toggleAiming();effect.update(.1,true);
 const reticle=scene.getObjectByName('psionic-ground-reticle');
 assert.equal(reticle.visible,true);
 assert.ok(reticle.children.every(mesh=>mesh.renderOrder>ground.renderOrder && mesh.material.depthTest));
 assert.equal(scene.children.some(node=>node.isLight),false);
 const up=new THREE.Vector3(0,1,0).applyQuaternion(reticle.quaternion);
 assert.ok(up.dot(new THREE.Vector3(-.5,1,0).normalize())>.999);
 reticle.updateMatrixWorld(true);
 const point=new THREE.Vector3().fromBufferAttribute(reticle.children[0].geometry.attributes.position,20).applyMatrix4(reticle.matrixWorld);
 assert.ok(Math.abs(point.y-point.x*.5-.15)<1e-4);
 camera.lookAt(0,100,0);camera.updateMatrixWorld(true);effect.update(.1,true);
 assert.equal(reticle.visible,false);
});
